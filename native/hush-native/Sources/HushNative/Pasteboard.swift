// The general pasteboard: snapshot and restore every type, change counting, and "transient"
// markers so clipboard managers skip what we paste.

import AppKit

enum Pasteboard {
    typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private static var pb: NSPasteboard { .general }

    static var changeCount: Int { pb.changeCount }

    static func snapshot() -> Snapshot? {
        guard let items = pb.pasteboardItems else { return nil }
        return items.map { item in
            item.types.compactMap { ty in item.data(forType: ty).map { (ty, $0) } }
        }
    }

    static func restore(_ snap: Snapshot) {
        pb.clearContents()
        if snap.isEmpty { return }
        let items = snap.map { entries in
            let item = NSPasteboardItem()
            for (ty, data) in entries { item.setData(data, forType: ty) }
            return item
        }
        pb.writeObjects(items)
    }

    /// Put text on the pasteboard and return the new change count. `transient` marks it so
    /// clipboard managers skip it.
    static func setText(_ text: String, transient: Bool) -> Int {
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient {
            for ty in [
                "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
                "org.nspasteboard.AutoGeneratedType",
            ] {
                item.setData(Data(), forType: NSPasteboard.PasteboardType(ty))
            }
        }
        pb.writeObjects([item])
        return pb.changeCount
    }

    static func text() -> String? { pb.string(forType: .string) }
}
